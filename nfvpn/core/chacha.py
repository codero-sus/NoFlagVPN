"""ChaCha20 keystream generation, in two interchangeable kernels.

Two implementations live here on purpose:

* :func:`chacha20_block` — one 64-byte block, 32-bit words in plain Python ints.
  This is the one the RFC 8439 test vectors pin down, and the one a reader
  should consult to check we implemented ChaCha20 and not something adjacent.
* :func:`_chacha20_blocks_packed` — 16 blocks per call, the entire state held in
  a single Python integer with one 64-bit lane per block.  Around fifteen times
  faster in CPython, because the interpreter then pays for ~1000 bigint ops
  instead of ~1000 ops per *block*.

Both are generated from ``tools/gen_chacha.py`` (see that file for the lane
argument to keep it correct), both are tested against the RFC vectors, and
``tests/test_chacha.py`` differentially tests them against each other on random
key/nonce/counter/length combinations.  Set ``NFVPN_CHACHA_SCALAR=1`` to force
the scalar kernel — useful under PyPy (where the simple loop JITs beautifully)
or when hunting a discrepancy.

XOR note: the last step of every encryption is ``plaintext XOR keystream`` over
the whole record.  Doing that byte-by-byte in Python is slower than the cipher
itself, so whole buffers are XORed as big integers, which is one C-level
operation per record.
"""

from __future__ import annotations

import os
import struct

__all__ = [
    "BLOCK_SIZE",
    "KEY_SIZE",
    "NONCE_SIZE",
    "PACKED_LANES",
    "chacha20_block",
    "chacha20_keystream",
    "chacha20_xor",
    "packed_kernel_available",
]

BLOCK_SIZE = 64
KEY_SIZE = 32
NONCE_SIZE = 12

#: Blocks computed per call by the packed kernel (must match the generated code).
PACKED_LANES = 16

_MASK32 = 0xFFFFFFFF
_WORD = 0xFFFFFFFF
_MAX_BLOCK_COUNTER = 0xFFFFFFFF

#: ChaCha20 state constants: the ASCII string "expand 32-byte k".
_C0 = 0x61707865
_C1 = 0x3320646E
_C2 = 0x79622D32
_C3 = 0x6B206574

#: Packed-kernel lane geometry.  Lane *j* of the state integer occupies bits
#: ``[64*j, 64*j + 64)`` and holds the 32-bit word of block ``counter + j``.
_ONES = sum(1 << (64 * lane) for lane in range(PACKED_LANES))
_LANE_IDS = sum(lane << (64 * lane) for lane in range(PACKED_LANES))
_MASK = sum(_WORD << (64 * lane) for lane in range(PACKED_LANES))
_LANE_SHIFTS = tuple(64 * lane for lane in range(PACKED_LANES))

#: Below this many bytes the big-integer XOR costs more than it saves.
_BIGINT_XOR_THRESHOLD = 256

_FORCE_SCALAR = os.environ.get("NFVPN_CHACHA_SCALAR", "").strip().lower() in {
    "1",
    "true",
    "yes",
    "on",
}


def packed_kernel_available() -> bool:
    """Whether :func:`chacha20_xor` is currently using the packed kernel."""
    return not _FORCE_SCALAR


def _validate(key: bytes, counter: int, nonce: bytes, length: int = 0) -> None:
    if len(key) != KEY_SIZE:
        raise ValueError(f"ChaCha20 key must be {KEY_SIZE} bytes, got {len(key)}")
    if len(nonce) != NONCE_SIZE:
        raise ValueError(f"ChaCha20 nonce must be {NONCE_SIZE} bytes, got {len(nonce)}")
    if not 0 <= counter <= _MAX_BLOCK_COUNTER:
        raise ValueError("ChaCha20 block counter must fit in 32 bits")
    if length and counter + (length + BLOCK_SIZE - 1) // BLOCK_SIZE > _MAX_BLOCK_COUNTER + 1:
        raise ValueError("ChaCha20 counter would overflow 2^32 blocks")


def chacha20_block(key: bytes, counter: int, nonce: bytes) -> bytes:
    """Return the 64-byte keystream block for this key, counter and nonce.

    RFC 8439 §2.3, written out flat over ``x0..x15``: ten double rounds, then
    the initial state added back word-wise.
    """
    _validate(key, counter, nonce)
    # --- BEGIN GENERATED SCALAR KERNEL — generated by tools/gen_chacha.py, do not edit by hand ---
    k0, k1, k2, k3, k4, k5, k6, k7 = struct.unpack("<8I", key)
    n0, n1, n2 = struct.unpack("<3I", nonce)

    x0 = s0 = _C0
    x1 = s1 = _C1
    x2 = s2 = _C2
    x3 = s3 = _C3
    x4 = s4 = k0
    x5 = s5 = k1
    x6 = s6 = k2
    x7 = s7 = k3
    x8 = s8 = k4
    x9 = s9 = k5
    x10 = s10 = k6
    x11 = s11 = k7
    x12 = s12 = counter
    x13 = s13 = n0
    x14 = s14 = n1
    x15 = s15 = n2

    for _ in range(10):
        # QUARTERROUND(0, 4, 8, 12)
        x0 = (x0 + x4) & _MASK32
        x12 ^= x0
        x12 = ((x12 << 16) | (x12 >> 16)) & _MASK32
        x8 = (x8 + x12) & _MASK32
        x4 ^= x8
        x4 = ((x4 << 12) | (x4 >> 20)) & _MASK32
        x0 = (x0 + x4) & _MASK32
        x12 ^= x0
        x12 = ((x12 << 8) | (x12 >> 24)) & _MASK32
        x8 = (x8 + x12) & _MASK32
        x4 ^= x8
        x4 = ((x4 << 7) | (x4 >> 25)) & _MASK32
        # QUARTERROUND(1, 5, 9, 13)
        x1 = (x1 + x5) & _MASK32
        x13 ^= x1
        x13 = ((x13 << 16) | (x13 >> 16)) & _MASK32
        x9 = (x9 + x13) & _MASK32
        x5 ^= x9
        x5 = ((x5 << 12) | (x5 >> 20)) & _MASK32
        x1 = (x1 + x5) & _MASK32
        x13 ^= x1
        x13 = ((x13 << 8) | (x13 >> 24)) & _MASK32
        x9 = (x9 + x13) & _MASK32
        x5 ^= x9
        x5 = ((x5 << 7) | (x5 >> 25)) & _MASK32
        # QUARTERROUND(2, 6, 10, 14)
        x2 = (x2 + x6) & _MASK32
        x14 ^= x2
        x14 = ((x14 << 16) | (x14 >> 16)) & _MASK32
        x10 = (x10 + x14) & _MASK32
        x6 ^= x10
        x6 = ((x6 << 12) | (x6 >> 20)) & _MASK32
        x2 = (x2 + x6) & _MASK32
        x14 ^= x2
        x14 = ((x14 << 8) | (x14 >> 24)) & _MASK32
        x10 = (x10 + x14) & _MASK32
        x6 ^= x10
        x6 = ((x6 << 7) | (x6 >> 25)) & _MASK32
        # QUARTERROUND(3, 7, 11, 15)
        x3 = (x3 + x7) & _MASK32
        x15 ^= x3
        x15 = ((x15 << 16) | (x15 >> 16)) & _MASK32
        x11 = (x11 + x15) & _MASK32
        x7 ^= x11
        x7 = ((x7 << 12) | (x7 >> 20)) & _MASK32
        x3 = (x3 + x7) & _MASK32
        x15 ^= x3
        x15 = ((x15 << 8) | (x15 >> 24)) & _MASK32
        x11 = (x11 + x15) & _MASK32
        x7 ^= x11
        x7 = ((x7 << 7) | (x7 >> 25)) & _MASK32
        # QUARTERROUND(0, 5, 10, 15)
        x0 = (x0 + x5) & _MASK32
        x15 ^= x0
        x15 = ((x15 << 16) | (x15 >> 16)) & _MASK32
        x10 = (x10 + x15) & _MASK32
        x5 ^= x10
        x5 = ((x5 << 12) | (x5 >> 20)) & _MASK32
        x0 = (x0 + x5) & _MASK32
        x15 ^= x0
        x15 = ((x15 << 8) | (x15 >> 24)) & _MASK32
        x10 = (x10 + x15) & _MASK32
        x5 ^= x10
        x5 = ((x5 << 7) | (x5 >> 25)) & _MASK32
        # QUARTERROUND(1, 6, 11, 12)
        x1 = (x1 + x6) & _MASK32
        x12 ^= x1
        x12 = ((x12 << 16) | (x12 >> 16)) & _MASK32
        x11 = (x11 + x12) & _MASK32
        x6 ^= x11
        x6 = ((x6 << 12) | (x6 >> 20)) & _MASK32
        x1 = (x1 + x6) & _MASK32
        x12 ^= x1
        x12 = ((x12 << 8) | (x12 >> 24)) & _MASK32
        x11 = (x11 + x12) & _MASK32
        x6 ^= x11
        x6 = ((x6 << 7) | (x6 >> 25)) & _MASK32
        # QUARTERROUND(2, 7, 8, 13)
        x2 = (x2 + x7) & _MASK32
        x13 ^= x2
        x13 = ((x13 << 16) | (x13 >> 16)) & _MASK32
        x8 = (x8 + x13) & _MASK32
        x7 ^= x8
        x7 = ((x7 << 12) | (x7 >> 20)) & _MASK32
        x2 = (x2 + x7) & _MASK32
        x13 ^= x2
        x13 = ((x13 << 8) | (x13 >> 24)) & _MASK32
        x8 = (x8 + x13) & _MASK32
        x7 ^= x8
        x7 = ((x7 << 7) | (x7 >> 25)) & _MASK32
        # QUARTERROUND(3, 4, 9, 14)
        x3 = (x3 + x4) & _MASK32
        x14 ^= x3
        x14 = ((x14 << 16) | (x14 >> 16)) & _MASK32
        x9 = (x9 + x14) & _MASK32
        x4 ^= x9
        x4 = ((x4 << 12) | (x4 >> 20)) & _MASK32
        x3 = (x3 + x4) & _MASK32
        x14 ^= x3
        x14 = ((x14 << 8) | (x14 >> 24)) & _MASK32
        x9 = (x9 + x14) & _MASK32
        x4 ^= x9
        x4 = ((x4 << 7) | (x4 >> 25)) & _MASK32

    x0 = (x0 + s0) & _MASK32
    x1 = (x1 + s1) & _MASK32
    x2 = (x2 + s2) & _MASK32
    x3 = (x3 + s3) & _MASK32
    x4 = (x4 + s4) & _MASK32
    x5 = (x5 + s5) & _MASK32
    x6 = (x6 + s6) & _MASK32
    x7 = (x7 + s7) & _MASK32
    x8 = (x8 + s8) & _MASK32
    x9 = (x9 + s9) & _MASK32
    x10 = (x10 + s10) & _MASK32
    x11 = (x11 + s11) & _MASK32
    x12 = (x12 + s12) & _MASK32
    x13 = (x13 + s13) & _MASK32
    x14 = (x14 + s14) & _MASK32
    x15 = (x15 + s15) & _MASK32

    return struct.pack(
        "<16I", x0, x1, x2, x3, x4, x5, x6, x7, x8, x9, x10, x11, x12, x13, x14, x15
    )
    # --- END GENERATED SCALAR KERNEL ---


def _chacha20_blocks_packed(key: bytes, counter: int, nonce: bytes) -> list[bytes]:
    """Return :data:`PACKED_LANES` consecutive blocks, computed 16 at a time.

    The returned list is blocks ``counter`` … ``counter + PACKED_LANES - 1``.
    Callers slice off whatever tail they do not need, which is cheaper than
    dropping back to the scalar kernel for a partial batch.
    """
    _validate(key, counter, nonce)
    # --- BEGIN GENERATED PACKED KERNEL — generated by tools/gen_chacha.py, do not edit by hand ---
    # 16 blocks per call: one integer, one 64-bit lane per block.
    k0, k1, k2, k3, k4, k5, k6, k7 = struct.unpack("<8I", key)
    n0, n1, n2 = struct.unpack("<3I", nonce)

    x0 = s0 = _C0 * _ONES
    x1 = s1 = _C1 * _ONES
    x2 = s2 = _C2 * _ONES
    x3 = s3 = _C3 * _ONES
    x4 = s4 = k0 * _ONES
    x5 = s5 = k1 * _ONES
    x6 = s6 = k2 * _ONES
    x7 = s7 = k3 * _ONES
    x8 = s8 = k4 * _ONES
    x9 = s9 = k5 * _ONES
    x10 = s10 = k6 * _ONES
    x11 = s11 = k7 * _ONES
    x12 = s12 = counter * _ONES + _LANE_IDS
    x13 = s13 = n0 * _ONES
    x14 = s14 = n1 * _ONES
    x15 = s15 = n2 * _ONES

    for _ in range(10):
        # QUARTERROUND(0, 4, 8, 12)
        x0 = (x0 + x4) & _MASK
        x12 ^= x0
        x12 = ((x12 << 16) | (x12 >> 16)) & _MASK
        x8 = (x8 + x12) & _MASK
        x4 ^= x8
        x4 = ((x4 << 12) | (x4 >> 20)) & _MASK
        x0 = (x0 + x4) & _MASK
        x12 ^= x0
        x12 = ((x12 << 8) | (x12 >> 24)) & _MASK
        x8 = (x8 + x12) & _MASK
        x4 ^= x8
        x4 = ((x4 << 7) | (x4 >> 25)) & _MASK
        # QUARTERROUND(1, 5, 9, 13)
        x1 = (x1 + x5) & _MASK
        x13 ^= x1
        x13 = ((x13 << 16) | (x13 >> 16)) & _MASK
        x9 = (x9 + x13) & _MASK
        x5 ^= x9
        x5 = ((x5 << 12) | (x5 >> 20)) & _MASK
        x1 = (x1 + x5) & _MASK
        x13 ^= x1
        x13 = ((x13 << 8) | (x13 >> 24)) & _MASK
        x9 = (x9 + x13) & _MASK
        x5 ^= x9
        x5 = ((x5 << 7) | (x5 >> 25)) & _MASK
        # QUARTERROUND(2, 6, 10, 14)
        x2 = (x2 + x6) & _MASK
        x14 ^= x2
        x14 = ((x14 << 16) | (x14 >> 16)) & _MASK
        x10 = (x10 + x14) & _MASK
        x6 ^= x10
        x6 = ((x6 << 12) | (x6 >> 20)) & _MASK
        x2 = (x2 + x6) & _MASK
        x14 ^= x2
        x14 = ((x14 << 8) | (x14 >> 24)) & _MASK
        x10 = (x10 + x14) & _MASK
        x6 ^= x10
        x6 = ((x6 << 7) | (x6 >> 25)) & _MASK
        # QUARTERROUND(3, 7, 11, 15)
        x3 = (x3 + x7) & _MASK
        x15 ^= x3
        x15 = ((x15 << 16) | (x15 >> 16)) & _MASK
        x11 = (x11 + x15) & _MASK
        x7 ^= x11
        x7 = ((x7 << 12) | (x7 >> 20)) & _MASK
        x3 = (x3 + x7) & _MASK
        x15 ^= x3
        x15 = ((x15 << 8) | (x15 >> 24)) & _MASK
        x11 = (x11 + x15) & _MASK
        x7 ^= x11
        x7 = ((x7 << 7) | (x7 >> 25)) & _MASK
        # QUARTERROUND(0, 5, 10, 15)
        x0 = (x0 + x5) & _MASK
        x15 ^= x0
        x15 = ((x15 << 16) | (x15 >> 16)) & _MASK
        x10 = (x10 + x15) & _MASK
        x5 ^= x10
        x5 = ((x5 << 12) | (x5 >> 20)) & _MASK
        x0 = (x0 + x5) & _MASK
        x15 ^= x0
        x15 = ((x15 << 8) | (x15 >> 24)) & _MASK
        x10 = (x10 + x15) & _MASK
        x5 ^= x10
        x5 = ((x5 << 7) | (x5 >> 25)) & _MASK
        # QUARTERROUND(1, 6, 11, 12)
        x1 = (x1 + x6) & _MASK
        x12 ^= x1
        x12 = ((x12 << 16) | (x12 >> 16)) & _MASK
        x11 = (x11 + x12) & _MASK
        x6 ^= x11
        x6 = ((x6 << 12) | (x6 >> 20)) & _MASK
        x1 = (x1 + x6) & _MASK
        x12 ^= x1
        x12 = ((x12 << 8) | (x12 >> 24)) & _MASK
        x11 = (x11 + x12) & _MASK
        x6 ^= x11
        x6 = ((x6 << 7) | (x6 >> 25)) & _MASK
        # QUARTERROUND(2, 7, 8, 13)
        x2 = (x2 + x7) & _MASK
        x13 ^= x2
        x13 = ((x13 << 16) | (x13 >> 16)) & _MASK
        x8 = (x8 + x13) & _MASK
        x7 ^= x8
        x7 = ((x7 << 12) | (x7 >> 20)) & _MASK
        x2 = (x2 + x7) & _MASK
        x13 ^= x2
        x13 = ((x13 << 8) | (x13 >> 24)) & _MASK
        x8 = (x8 + x13) & _MASK
        x7 ^= x8
        x7 = ((x7 << 7) | (x7 >> 25)) & _MASK
        # QUARTERROUND(3, 4, 9, 14)
        x3 = (x3 + x4) & _MASK
        x14 ^= x3
        x14 = ((x14 << 16) | (x14 >> 16)) & _MASK
        x9 = (x9 + x14) & _MASK
        x4 ^= x9
        x4 = ((x4 << 12) | (x4 >> 20)) & _MASK
        x3 = (x3 + x4) & _MASK
        x14 ^= x3
        x14 = ((x14 << 8) | (x14 >> 24)) & _MASK
        x9 = (x9 + x14) & _MASK
        x4 ^= x9
        x4 = ((x4 << 7) | (x4 >> 25)) & _MASK

    x0 = (x0 + s0) & _MASK
    x1 = (x1 + s1) & _MASK
    x2 = (x2 + s2) & _MASK
    x3 = (x3 + s3) & _MASK
    x4 = (x4 + s4) & _MASK
    x5 = (x5 + s5) & _MASK
    x6 = (x6 + s6) & _MASK
    x7 = (x7 + s7) & _MASK
    x8 = (x8 + s8) & _MASK
    x9 = (x9 + s9) & _MASK
    x10 = (x10 + s10) & _MASK
    x11 = (x11 + s11) & _MASK
    x12 = (x12 + s12) & _MASK
    x13 = (x13 + s13) & _MASK
    x14 = (x14 + s14) & _MASK
    x15 = (x15 + s15) & _MASK

    return [
        struct.pack(
            "<16I",
            (x0 >> shift) & _WORD,
            (x1 >> shift) & _WORD,
            (x2 >> shift) & _WORD,
            (x3 >> shift) & _WORD,
            (x4 >> shift) & _WORD,
            (x5 >> shift) & _WORD,
            (x6 >> shift) & _WORD,
            (x7 >> shift) & _WORD,
            (x8 >> shift) & _WORD,
            (x9 >> shift) & _WORD,
            (x10 >> shift) & _WORD,
            (x11 >> shift) & _WORD,
            (x12 >> shift) & _WORD,
            (x13 >> shift) & _WORD,
            (x14 >> shift) & _WORD,
            (x15 >> shift) & _WORD,
        )
        for shift in _LANE_SHIFTS
    ]
    # --- END GENERATED PACKED KERNEL ---


def chacha20_keystream(key: bytes, counter: int, nonce: bytes, length: int) -> bytes:
    """Return ``length`` bytes of ChaCha20 keystream."""
    if length < 0:
        raise ValueError("length must be non-negative")
    if length == 0:
        return b""
    _validate(key, counter, nonce, length)

    blocks = (length + BLOCK_SIZE - 1) // BLOCK_SIZE
    chunks: list[bytes] = []

    if _FORCE_SCALAR or blocks == 1:
        chunks.extend(chacha20_block(key, counter + index, nonce) for index in range(blocks))
    else:
        batches = blocks // PACKED_LANES
        for index in range(batches):
            chunks.extend(
                _chacha20_blocks_packed(key, counter + index * PACKED_LANES, nonce)
            )
        leftover = blocks - batches * PACKED_LANES
        if leftover:
            # Over-generate one batch and let the final slice trim it: a full
            # packed batch is cheaper than `leftover` scalar blocks.
            chunks.extend(
                _chacha20_blocks_packed(key, counter + batches * PACKED_LANES, nonce)
            )

    return b"".join(chunks)[:length]


def chacha20_xor(key: bytes, counter: int, nonce: bytes, data: bytes) -> bytes:
    """Encrypt or decrypt ``data`` (ChaCha20 is its own inverse).

    Use ``counter = 1`` for AEAD payloads so block 0 stays reserved for the
    Poly1305 one-time key.
    """
    if not data:
        return b""
    stream = chacha20_keystream(key, counter, nonce, len(data))
    if len(data) < _BIGINT_XOR_THRESHOLD:
        return bytes(map(int.__xor__, data, stream))
    return (
        int.from_bytes(data, "big") ^ int.from_bytes(stream, "big")
    ).to_bytes(len(data), "big")
