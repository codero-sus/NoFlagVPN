#!/usr/bin/env python3
"""Generate the flat ChaCha20 inner loops checked into ``nfvpn/core/chacha.py``.

Why generate code at all?
-------------------------
The inner loop of ChaCha20 is 10 double rounds of 8 quarter rounds.  In CPython,
looping over that structure costs far more than the arithmetic does, so the
quarter rounds are written out flat over 16 local names.  Writing ~1000 lines of
that by hand would be a bug farm, so it is emitted and checked into the tree:
``nfvpn/core/chacha.py`` holds two generated regions between marker comments and
``--check`` verifies the tree is still in sync with this script.

Two kernels are emitted from the same source text:

``scalar``  one 64-byte block at a time, 32-bit words in 32-bit locals.  This is
            the reference: it is what the RFC test vectors pin, and what the
            packed kernel is differentially tested against.
``packed``  16 blocks at a time, the whole state held in one Python integer with
            one 64-bit lane per block.

The packing trick
-----------------
``_ONES`` has a 1 at the bottom of every lane, so ``constant * _ONES`` replicates
a constant across all lanes, and ``_LANE_IDS`` adds the lane index to each lane's
block counter.  Each lane is 64 bits wide while its word stays 32 bits, which
buys two things:

* adding two lanes can never carry into the neighbouring lane (the sum is
  < 2^33, the lane is 64 bits wide), and
* the rotate-left-32 idiom ``((v << n) | (v >> (32 - n))) & _MASK`` works lane by
  lane, because bits that the right shift drags in from the next lane land above
  bit 32 and vanish under the mask.

One caveat, which cost an afternoon: every addition must be masked *immediately*.
An unmasked 33-bit intermediate leaks its carry bit into the next rotation's wrap
position, which silently corrupts the output for some inputs only -- exactly the
kind of bug the RFC vectors and ``tests/test_chacha.py`` exist to catch.

Usage
-----
    python tools/gen_chacha.py --write     # regenerate the regions in chacha.py
    python tools/gen_chacha.py --check     # CI: fail if the tree is out of date
    python tools/gen_chacha.py --print     # show the generated source
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
TARGET = REPO_ROOT / "nfvpn" / "core" / "chacha.py"

PACKED_LANES = 16

#: QUARTERROUND index schedule for one double round (RFC 8439 §2.3).
QUARTER_ROUNDS = (
    (0, 4, 8, 12),
    (1, 5, 9, 13),
    (2, 6, 10, 14),
    (3, 7, 11, 15),
    (0, 5, 10, 15),
    (1, 6, 11, 12),
    (2, 7, 8, 13),
    (3, 4, 9, 14),
)

#: The 16 words of the packed initial state.
PACKED_INITIAL_WORDS = (
    "_C0 * _ONES",
    "_C1 * _ONES",
    "_C2 * _ONES",
    "_C3 * _ONES",
    "k0 * _ONES",
    "k1 * _ONES",
    "k2 * _ONES",
    "k3 * _ONES",
    "k4 * _ONES",
    "k5 * _ONES",
    "k6 * _ONES",
    "k7 * _ONES",
    "counter * _ONES + _LANE_IDS",
    "n0 * _ONES",
    "n1 * _ONES",
    "n2 * _ONES",
)


def _quarter_rounds(indent: int, mask: str) -> str:
    """The 8 quarter rounds of one double round, flat, over locals ``x0..x15``."""
    pad = " " * indent
    lines: list[str] = []
    for a, b, c, d in QUARTER_ROUNDS:
        lines.append(f"{pad}# QUARTERROUND({a}, {b}, {c}, {d})")
        lines.append(f"{pad}x{a} = (x{a} + x{b}) & {mask}")
        lines.append(f"{pad}x{d} ^= x{a}")
        lines.append(f"{pad}x{d} = ((x{d} << 16) | (x{d} >> 16)) & {mask}")
        lines.append(f"{pad}x{c} = (x{c} + x{d}) & {mask}")
        lines.append(f"{pad}x{b} ^= x{c}")
        lines.append(f"{pad}x{b} = ((x{b} << 12) | (x{b} >> 20)) & {mask}")
        lines.append(f"{pad}x{a} = (x{a} + x{b}) & {mask}")
        lines.append(f"{pad}x{d} ^= x{a}")
        lines.append(f"{pad}x{d} = ((x{d} << 8) | (x{d} >> 24)) & {mask}")
        lines.append(f"{pad}x{c} = (x{c} + x{d}) & {mask}")
        lines.append(f"{pad}x{b} ^= x{c}")
        lines.append(f"{pad}x{b} = ((x{b} << 7) | (x{b} >> 25)) & {mask}")
    return "\n".join(lines)


def generate_scalar() -> str:
    """Flat single-block kernel: 32-bit words, 32-bit locals."""
    setup = "\n".join(
        f"    x{i} = s{i} = {word}"
        for i, word in enumerate(
            (
                "_C0", "_C1", "_C2", "_C3",
                "k0", "k1", "k2", "k3", "k4", "k5", "k6", "k7",
                "counter", "n0", "n1", "n2",
            )
        )
    )
    add_back = "\n".join(f"    x{i} = (x{i} + s{i}) & _MASK32" for i in range(16))
    return f"""{SCALAR_BEGIN} — generated by tools/gen_chacha.py, do not edit by hand ---
    k0, k1, k2, k3, k4, k5, k6, k7 = struct.unpack("<8I", key)
    n0, n1, n2 = struct.unpack("<3I", nonce)

{setup}

    for _ in range(10):
{_quarter_rounds(8, "_MASK32")}

{add_back}

    return struct.pack(
        "<16I", x0, x1, x2, x3, x4, x5, x6, x7, x8, x9, x10, x11, x12, x13, x14, x15
    )
{SCALAR_END}
"""


def generate_packed(lanes: int = PACKED_LANES) -> str:
    """Flat multi-block kernel: 64-bit lanes, 16 blocks per call."""
    if lanes < 2:
        raise ValueError("the packed kernel is pointless below two lanes")

    setup = "\n".join(
        f"    x{i} = s{i} = {word}" for i, word in enumerate(PACKED_INITIAL_WORDS)
    )
    add_back = "\n".join(f"    x{i} = (x{i} + s{i}) & _MASK" for i in range(16))
    pack_words = ",\n            ".join(f"(x{i} >> shift) & _WORD" for i in range(16))

    return f"""{PACKED_BEGIN} — generated by tools/gen_chacha.py, do not edit by hand ---
    # {lanes} blocks per call: one integer, one 64-bit lane per block.
    k0, k1, k2, k3, k4, k5, k6, k7 = struct.unpack("<8I", key)
    n0, n1, n2 = struct.unpack("<3I", nonce)

{setup}

    for _ in range(10):
{_quarter_rounds(8, "_MASK")}

{add_back}

    return [
        struct.pack(
            "<16I",
            {pack_words},
        )
        for shift in _LANE_SHIFTS
    ]
{PACKED_END}
"""


SCALAR_BEGIN = "    # --- BEGIN GENERATED SCALAR KERNEL"
SCALAR_END = "    # --- END GENERATED SCALAR KERNEL ---"
PACKED_BEGIN = "    # --- BEGIN GENERATED PACKED KERNEL"
PACKED_END = "    # --- END GENERATED PACKED KERNEL ---"

REGIONS: tuple[tuple[str, str], ...] = (
    (SCALAR_BEGIN, SCALAR_END),
    (PACKED_BEGIN, PACKED_END),
)


def generated_regions(lanes: int = PACKED_LANES) -> list[tuple[str, str]]:
    """``[(begin_marker, generated_text), …]`` for every region."""
    return [
        (SCALAR_BEGIN, generate_scalar()),
        (PACKED_BEGIN, generate_packed(lanes)),
    ]


def _region_span(text: str, begin: str, end: str) -> tuple[int, int]:
    start = text.index(begin)
    start = text.rfind("\n", 0, start) + 1
    stop = text.index(end, start) + len(end)
    newline = text.find("\n", stop)
    return start, (len(text) if newline == -1 else newline + 1)


def apply_regions(text: str, regions: list[tuple[str, str]], lanes: int) -> str:
    """Replace every generated region in ``text`` with freshly generated text."""
    generated = dict(generated_regions(lanes))
    for begin, _ in regions:
        start, stop = _region_span(text, begin, dict(REGIONS)[begin])
        text = text[:start] + generated[begin] + text[stop:]
    return text


def check_regions(text: str, regions: list[tuple[str, str]], lanes: int) -> list[str]:
    """Return the markers whose content does not match freshly generated text."""
    generated = dict(generated_regions(lanes))
    stale: list[str] = []
    for begin, _ in regions:
        start, stop = _region_span(text, begin, dict(REGIONS)[begin])
        if text[start:stop] != generated[begin]:
            stale.append(begin.split("BEGIN ")[-1].split(" KERNEL")[0])
    return stale


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--lanes", type=int, default=PACKED_LANES)
    parser.add_argument("--check", action="store_true", help="fail if out of date")
    parser.add_argument("--write", action="store_true", help="rewrite chacha.py")
    parser.add_argument("--print", dest="emit", action="store_true", help="print it")
    args = parser.parse_args(argv)

    regions = list(REGIONS)

    if args.emit:
        for _, text in generated_regions(args.lanes):
            print(text)
        return 0

    if not TARGET.exists():
        print(f"error: {TARGET} does not exist", file=sys.stderr)
        return 2

    original = TARGET.read_text(encoding="utf-8")

    if args.check:
        stale = check_regions(original, regions, args.lanes)
        if stale:
            print(
                f"{TARGET.relative_to(REPO_ROOT)}: stale generated region(s): "
                f"{', '.join(stale)}\nrun `python tools/gen_chacha.py --write`",
                file=sys.stderr,
            )
            return 1
        print(f"{TARGET.name}: generated kernels are in sync ({args.lanes} lanes)")
        return 0

    if args.write:
        TARGET.write_text(apply_regions(original, regions, args.lanes), encoding="utf-8")
        print(f"wrote {TARGET.relative_to(REPO_ROOT)} ({args.lanes} lanes)")
        return 0

    parser.print_help()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
